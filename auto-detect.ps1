$base = $PSScriptRoot
$eventsDir = Join-Path -Path $base -ChildPath "events"
$dataFile = Join-Path -Path $base -ChildPath "events-data.json"
$outputFile = Join-Path -Path $base -ChildPath "events-data.js"

Clear-Host
Write-Host "==================================================" -ForegroundColor Magenta
Write-Host "   >>> ARC LANDING PAGE AUTO-DETECTOR IS RUNNING! <<< " -ForegroundColor Cyan
Write-Host "==================================================" -ForegroundColor Magenta
Write-Host ""
Write-Host "1. Keep this black window open in the background." -ForegroundColor White
Write-Host "2. Drop your images/videos into the 'events' folders." -ForegroundColor White
Write-Host "3. This script will instantly detect them and update the site!" -ForegroundColor White
Write-Host ""
Write-Host "Press Ctrl+C to stop it when you're done working.`n" -ForegroundColor Gray

$lastState = ""

while ($true) {
    # Check for changes in the events directory and the data file
    if (Test-Path $eventsDir) {
        $dirState = Get-ChildItem -Path $eventsDir -Recurse -File | Select-Object FullName, Length, LastWriteTime | Out-String
        $jsonState = ""
        if (Test-Path $dataFile) {
            $jsonState = Get-Item -Path $dataFile | Select-Object Length, LastWriteTime | Out-String
        }
        $currentState = $dirState + $jsonState
        
        if ($currentState -ne $lastState) {
            if ($lastState -ne "") {
                Write-Host "[$(Get-Date -Format 'HH:mm:ss')] -> File change detected! Updating website..." -ForegroundColor Green
            }
            
            $lastState = $currentState
            
            # Read Data
            $eventsJson = Get-Content -Raw -Path $dataFile
            $events = $eventsJson | ConvertFrom-Json

            foreach ($event in $events) {
                $eventId = $event.id
                $eventFolder = Join-Path -Path $eventsDir -ChildPath $eventId
                
                $media = @()
                if (Test-Path -Path $eventFolder) {
                    $files = Get-ChildItem -Path $eventFolder -File
                    
                    foreach ($file in $files) {
                        $ext = $file.Extension.ToLower()
                        $name = $file.Name.ToLower()
                        if ($ext -match "\.(jpg|jpeg|png|gif|mp4|webm)") {
                            if ($name -eq "cover.jpg" -or $name -eq "cover.jpeg" -or $name -eq "cover.png") {
                                $event.img = "events/$eventId/$($file.Name)"
                            } else {
                                $type = if ($ext -match "\.(mp4|webm)") { "video" } else { "image" }
                                $mediaItem = @{ type = $type; url = "events/$eventId/$($file.Name)" }
                                $media += $mediaItem
                            }
                        }
                    }
                }
                $event | Add-Member -NotePropertyName "media" -NotePropertyValue $media -Force
            }

            $outputJson = $events | ConvertTo-Json -Depth 10
            $finalContent = "// Automatically generated by Auto-Detector`nwindow.timelineEvents = $outputJson;"
            Set-Content -Path $outputFile -Value $finalContent
            
            if ($lastState -ne "") {
                Write-Host "[$(Get-Date -Format 'HH:mm:ss')] -> Done! You can refresh your browser now.`n" -ForegroundColor Yellow
            }
        }
    }
    
    Start-Sleep -Seconds 2
}
