const fs = require('fs');
const path = require('path');

const EVENTS_DIR = path.join(__dirname, 'events');
const DATA_JSON_FILE = path.join(__dirname, 'events-data.json');
const OUTPUT_JS_FILE = path.join(__dirname, 'events-data.js');

// Helper to check if it's a media file we want
const isMedia = (file) => {
    const ext = path.extname(file).toLowerCase();
    return ['.jpg', '.jpeg', '.png', '.gif', '.mp4', '.webm'].includes(ext);
};

// Main build function
function buildEventData() {
    console.log('Starting automated event folder scan...');
    
    // 1. Read the base event list
    let events = [];
    if (fs.existsSync(DATA_JSON_FILE)) {
        const rawData = fs.readFileSync(DATA_JSON_FILE, 'utf8');
        events = JSON.parse(rawData);
    } else {
        console.error('Error: events-data.json not found!');
        process.exit(1);
    }

    // 2. Scan folders
    if (!fs.existsSync(EVENTS_DIR)) {
        console.log('Creating events directory as it does not exist...');
        fs.mkdirSync(EVENTS_DIR);
    }

    // Enhance each event with media files found in its corresponding folder
    events = events.map(event => {
        const eventFolder = path.join(EVENTS_DIR, event.id);
        const mediaFiles = [];

        // Ensure the folder exists so the user can easily drop files in
        if (!fs.existsSync(eventFolder)) {
            console.log(`Creating empty folder for event: ${event.id}`);
            fs.mkdirSync(eventFolder, { recursive: true });
        } else {
            // Read all files in the folder
            const files = fs.readdirSync(eventFolder);
            
            files.forEach(file => {
                if (isMedia(file)) {
                    const lowerFile = file.toLowerCase();
                    if (lowerFile === 'cover.jpg' || lowerFile === 'cover.jpeg' || lowerFile === 'cover.png') {
                        event.img = `events/${event.id}/${file}`;
                    } else {
                        const isVideo = file.endsWith('.mp4') || file.endsWith('.webm');
                        mediaFiles.push({
                            type: isVideo ? 'video' : 'image',
                            url: `events/${event.id}/${file}`
                        });
                    }
                }
            });
        }
        
        // Sort files nicely (e.g. 1.jpg before 2.jpg)
        mediaFiles.sort((a, b) => {
            return a.url.localeCompare(b.url, undefined, { numeric: true, sensitivity: 'base' });
        });
        
        console.log(`Found ${mediaFiles.length} media files for ${event.id}`);
        return { ...event, media: mediaFiles };
    });

    // 3. Output standard JavaScript file
    const outputContent = `// Automatically generated by build.js\nwindow.timelineEvents = ${JSON.stringify(events, null, 2)};\n`;
    fs.writeFileSync(OUTPUT_JS_FILE, outputContent);
    console.log(`Successfully generated ${OUTPUT_JS_FILE}`);
}

buildEventData();
